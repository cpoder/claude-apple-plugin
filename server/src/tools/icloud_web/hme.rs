//! iCloud+ Hide My Email through the `premiummailsettings` web service (`/v1/hme`, `/v2/hme`),
//! as the icloud.com settings page does it: list aliases, generate + reserve a new one,
//! deactivate / reactivate, delete. No PCS step; every response carries a `result` envelope.

use rmcp::handler::server::wrapper::Parameters;
use rmcp::{tool, tool_router};
use serde::Deserialize;
use serde_json::{Value, json};

use super::{WebErr, WebSession};
use crate::error::ToolResult;
use crate::http::render;
use crate::server::AppleServer;

const DEFAULT_NOTE: &str = "Generated by Claude";

fn alias_json(e: &Value) -> Value {
    json!({
        "anonymous_id": e["anonymousId"],
        "email": e["hme"],
        "label": e["label"],
        "note": e["note"],
        "active": e["isActive"],
        "forward_to": e["forwardToEmail"],
    })
}

impl WebSession {
    fn hme_url(&self, version: &str, path: &str) -> Result<String, WebErr> {
        Ok(format!("{}/{version}/hme/{path}", self.ws_url("premiummailsettings")?))
    }

    /// `result` of a Hide My Email response (the envelope's only useful key).
    fn hme_result(v: Value) -> Value {
        match v.get("result") {
            Some(r) => r.clone(),
            None => Value::Null,
        }
    }

    /// `POST /v1/hme/<path>` with a JSON body; returns `result`.
    async fn hme_post(&self, version: &str, path: &str, body: &Value) -> Result<Value, WebErr> {
        let v = self.post(&self.hme_url(version, path)?, &[], body).await?;
        Ok(Self::hme_result(v))
    }

    /// All aliases (`GET /v2/hme/list`), raw Apple objects.
    pub async fn hme_list(&self) -> Result<Vec<Value>, WebErr> {
        let v = self.get(&self.hme_url("v2", "list")?, &[]).await?;
        Ok(Self::hme_result(v)["hmeEmails"].as_array().cloned().unwrap_or_default())
    }

    /// Ask Apple for a fresh alias address (`POST /v1/hme/generate`, empty body); not reserved yet.
    pub async fn hme_generate(&self) -> Result<String, WebErr> {
        let url = self.hme_url("v1", "generate")?;
        let r = self.raw(self.http.post(url).query(&self.params())).await?;
        let v = r.json().unwrap_or(Value::Null);
        Self::hme_result(v)["hme"]
            .as_str()
            .filter(|s| !s.is_empty())
            .map(String::from)
            .ok_or_else(|| WebErr::Other("Apple did not return an address (rate limited?)".into()))
    }

    /// Reserve a generated address with a label and note (`POST /v1/hme/reserve`).
    pub async fn hme_reserve(&self, email: &str, label: &str, note: &str) -> Result<Value, WebErr> {
        self.hme_post("v1", "reserve", &json!({"hme": email, "label": label, "note": note})).await
    }

    /// `deactivate` / `reactivate` / `delete` (`POST /v1/hme/<action>` with `{"anonymousId"}`).
    pub async fn hme_action(&self, action: &str, anonymous_id: &str) -> Result<Value, WebErr> {
        self.hme_post("v1", action, &json!({"anonymousId": anonymous_id})).await
    }
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct HmeCreateParams {
    /// Label shown in iCloud settings (e.g. the site or purpose the alias is for)
    pub label: String,
    /// Free-text note (default "Generated by Claude")
    pub note: Option<String>,
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct HmeSetActiveParams {
    /// Alias id (`anonymous_id` from icloud_hme_list)
    pub anonymous_id: String,
    /// true = reactivate (mail is forwarded again), false = deactivate (mail is rejected)
    pub active: bool,
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct HmeDeleteParams {
    /// Alias id (`anonymous_id` from icloud_hme_list)
    pub anonymous_id: String,
}

#[tool_router(router = icloud_hme_router, vis = "pub")]
impl AppleServer {
    /// List Hide My Email aliases of the iCloud+ account (address, label, note, active, forwarding address). Needs icloud_login first.
    #[tool(annotations(read_only_hint = true))]
    pub async fn icloud_hme_list(&self) -> ToolResult {
        let s = self.web().await?;
        let aliases: Vec<Value> = s.hme_list().await?.iter().map(alias_json).collect();
        Ok(render(&json!({"count": aliases.len(), "aliases": aliases})))
    }

    /// Create a new Hide My Email alias (Apple generates the address, then it is reserved with the given label and note).
    #[tool]
    pub async fn icloud_hme_create(&self, Parameters(p): Parameters<HmeCreateParams>) -> ToolResult {
        let s = self.web().await?;
        let label = p.label.trim();
        if label.is_empty() {
            crate::bail!("label must not be empty");
        }
        let email = s.hme_generate().await?;
        let note = p.note.as_deref().map(str::trim).filter(|n| !n.is_empty()).unwrap_or(DEFAULT_NOTE);
        let result = s.hme_reserve(&email, label, note).await?;
        let alias = if result.get("hme").is_some() || result.get("anonymousId").is_some() { Some(alias_json(&result)) } else { None };
        Ok(render(&json!({"email": email, "label": label, "note": note, "alias": alias, "result": result})))
    }

    /// Deactivate (stop forwarding) or reactivate a Hide My Email alias by its anonymous id.
    #[tool]
    pub async fn icloud_hme_set_active(&self, Parameters(p): Parameters<HmeSetActiveParams>) -> ToolResult {
        let s = self.web().await?;
        let id = p.anonymous_id.trim();
        if id.is_empty() {
            crate::bail!("anonymous_id must not be empty");
        }
        let action = if p.active { "reactivate" } else { "deactivate" };
        let result = s.hme_action(action, id).await?;
        Ok(render(&json!({"anonymous_id": id, "active": p.active, "action": action, "result": result})))
    }

    /// Permanently delete a Hide My Email alias by its anonymous id (mail sent to it will bounce; this cannot be undone).
    #[tool(annotations(destructive_hint = true))]
    pub async fn icloud_hme_delete(&self, Parameters(p): Parameters<HmeDeleteParams>) -> ToolResult {
        let s = self.web().await?;
        let id = p.anonymous_id.trim();
        if id.is_empty() {
            crate::bail!("anonymous_id must not be empty");
        }
        let result = s.hme_action("delete", id).await?;
        Ok(render(&json!({"deleted": id, "result": result})))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn alias_fields_mapped() {
        let a = alias_json(&json!({"anonymousId": "abc", "hme": "x.y@icloud.com", "label": "Shop", "note": "n", "isActive": true, "forwardToEmail": "me@example.com", "extra": 1}));
        assert_eq!(a, json!({"anonymous_id": "abc", "email": "x.y@icloud.com", "label": "Shop", "note": "n", "active": true, "forward_to": "me@example.com"}));
    }

    #[test]
    fn result_envelope() {
        assert_eq!(WebSession::hme_result(json!({"success": true, "result": {"hme": "a@b"}}))["hme"], "a@b");
        assert!(WebSession::hme_result(json!({"success": true})).is_null());
        assert!(WebSession::hme_result(json!({"result": {}}))["hmeEmails"].as_array().is_none());
    }
}
